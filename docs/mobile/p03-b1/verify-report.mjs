import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
const dir=fileURLToPath(new URL('.',import.meta.url)),root=resolve(dir,'../../..');
const read=p=>readFileSync(resolve(dir,p),'utf8').replace(/^\uFEFF/,'');
const json=p=>JSON.parse(read(p));
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex').toUpperCase();
const html=read('SUBWISE-P03-B1-REPORT.html'),a=json('evidence/acceptance.json');
assert.equal(a.overall,'BLOCKED');assert.equal(a.android.appLaunch,'NOT_RUN');assert.equal(a.android.build,'FAIL');
assert.ok(a.builds.every(b=>b.exitCode===1));
assert.ok(!existsSync(resolve(root,'mobile/p03-b/rn/android/app/build/outputs/apk/release/app-release.apk')));
for(const file of json('evidence/baseline.json'))assert.equal(hash(resolve(root,file.path)),file.sha256,file.path);
for(const artifact of a.artifacts)assert.equal(hash(resolve(dir,artifact.path)),artifact.sha256);
assert.ok(!/<script\b|<link\b|<iframe\b|@import|url\(/i.test(html));
assert.ok(html.includes('data:image/png;base64,')&&html.includes('不是Subwise App通过证据'));
for(const [,href] of html.matchAll(/href="([^"#]+)"/g))if(!href.startsWith('https://'))assert.ok(existsSync(resolve(dir,href)),href);
const zip=json('evidence/mac-archive-inspection.json');assert.ok(zip.safe);assert.ok(zip.entries.some(e=>e==='mobile/p03-b1/mac-verify.mjs'));
const result={status:'PASS',scope:'Report/evidence/handoff structural checks only; not native app acceptance',at:new Date().toISOString(),preservedFiles:a.baselinePreserved,offlineReport:true,artifactHashVerified:true,overallNativeGate:'BLOCKED'};
writeFileSync(resolve(dir,'evidence/report-validation.json'),JSON.stringify(result,null,2));console.log(result);
