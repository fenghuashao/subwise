import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const dir=fileURLToPath(new URL('.',import.meta.url));const root=resolve(dir,'../../..');
const read=p=>readFileSync(resolve(dir,p),'utf8').replace(/^\uFEFF/,'');const json=p=>JSON.parse(read(p));
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex').toUpperCase();
const html=read('SUBWISE-P03-B-REPORT.html');
assert.ok(html.includes('PARTIAL')&&html.includes('NOT_RUN')&&html.includes('无 APK'));
assert.ok(!/<script\b|<link\b|<iframe\b|@import|url\(/i.test(html));
assert.ok(!/(?:src|href)=["']https?:/i.test(html.replace(/<a\b[^>]*>/g,'')));
assert.ok(html.includes('data:image/png;base64,'));
const baseline=json('evidence/baseline.json');for(const item of baseline)assert.equal(hash(resolve(root,item.path)),item.sha256,item.path);
const manifest=json('evidence/source-manifest.json');for(const item of manifest)assert.equal(hash(resolve(root,item.path)),item.sha256,item.path);
assert.equal(json('evidence/acceptance.json').verdict,'PARTIAL');
for(const name of ['typecheck','tests','dependencies','expo-compatibility','native-js-bundle','web-bundle','android-prebuild']) assert.equal(json(`evidence/${name}.json`).exitCode,0,name);
assert.notEqual(json('evidence/android-assemble.json').exitCode,0);
assert.match(read('evidence/tests.log'),/pass 8/);
const browser=json('evidence/browser-observations.json');assert.match(browser.reloadState,/CNY 110.00/);assert.match(browser.failureState,/已保留最后成功记录/);assert.match(browser.notificationWebState,/NOT_RUN/);
const fixtures=JSON.parse(readFileSync(resolve(root,'mobile/p03-b/harmony/entry/src/main/resources/rawfile/fixtures.json')));
const shared=await import(pathToFileURL(resolve(root,'mobile/p03-b/rn/src/core.mjs')).href);assert.deepEqual(fixtures,{deepseek:shared.deepseekFixture,minimax:shared.minimaxFixture});
const result={status:'PASS',at:new Date().toISOString(),preservedFiles:baseline.length,manifestFiles:manifest.length,offlineResources:true,embeddedScreenshot:true,fixtureParity:true,nativeGate:'NOT_PASSED',scope:'Report/source checks only; not native acceptance'};
writeFileSync(resolve(dir,'evidence/report-validation.json'),JSON.stringify(result,null,2));console.log(result);
